test('Shanghai dates and Monday-based week boundaries',()=>{
  assert.equal(dayKey(Date.parse('2026-10-14T15:59:59Z')),'2026-10-14');
  assert.equal(dayKey(Date.parse('2026-10-14T16:00:00Z')),'2026-10-15');
  assert.equal(weekStart('2026-10-18'),'2026-10-12');
  assert.equal(weekStart('2026-10-19'),'2026-10-19');
  assert.equal(weekStart('2026-01-01'),'2025-12-29');
});
test('real multi-account lifecycle, private groups, scoring, withdrawal and deletion',async t=>{
  let now=Date.parse('2026-10-14T02:00:00Z');
  const s=createService({clock:()=>now});t.after(()=>s.close());
  const a=await register(s,'alice'),b=await register(s,'bob'),c=await register(s,'charlie');
  assert.notEqual(a.token,b.token);
  assert.equal(s.authenticate(a.token).id,a.user.id);
  await assert.rejects(()=>s.login({username:'alice',password:'wrong'}),e=>e.code==='LOGIN_FAILED');
  await assert.rejects(()=>s.register({username:'alice',nickname:'冒名',password,accepted:true}),e=>e.code==='USERNAME_TAKEN');
  await assert.rejects(()=>s.register({username:'dave',nickname:'D',password,accepted:false}),e=>e.code==='CONSENT_REQUIRED');
  const group=s.createGroup(a.user.id,{name:'一起成长',accepted:true});
  assert.throws(()=>s.board(b.user.id,group.id),e=>e.status===404);
  assert.throws(()=>s.newInvite(b.user.id,group.id),e=>e.status===404);
  const invite=s.newInvite(a.user.id,group.id);
  assert.equal(s.previewInvite(invite.code).name,'一起成长');
  assert.throws(()=>s.join(b.user.id,{code:invite.code,accepted:false}),e=>e.code==='CONSENT_REQUIRED');
  s.join(b.user.id,{code:invite.code,accepted:true});
  assert.throws(()=>s.join(c.user.id,{code:invite.code,accepted:true}),e=>e.code==='INVITE_UNAVAILABLE');
  assert.throws(()=>s.newInvite(b.user.id,group.id),e=>e.status===403);
  assert.equal(s.record(a.user.id,'checkin','daily').points,1);
  assert.equal(s.record(a.user.id,'checkin','daily').points,0);
  for(const id of ['focus','learn','move']){
    assert.equal(s.record(a.user.id,'action',id).points,2);
    assert.equal(s.record(a.user.id,'action',id).points,0);
  }
  assert.equal(s.summary(a.user.id).todayPoints,7);
  assert.equal(s.summary(b.user.id).todayPoints,0);
  assert.throws(()=>s.record(a.user.id,'action','custom-999'),e=>e.code==='UNKNOWN_ACTION');
  let board=s.board(b.user.id,group.id);
  assert.equal(board.rows[0].userId,a.user.id);assert.equal(board.rows[0].points,7);
  assert.equal(board.rows[1].points,0);
  for(const forbidden of ['password','username','token','earnings','expenses','finance','note'])assert.ok(!JSON.stringify(board.rows).includes(forbidden));
  s.record(b.user.id,'checkin','daily');for(const id of ['focus','learn','move'])s.record(b.user.id,'action',id);
  assert.deepEqual(s.board(a.user.id,group.id).rows.map(x=>x.rank),[1,1],'Ties share rank');
  s.setRanking(b.user.id,group.id,false);
  assert.equal(s.board(a.user.id,group.id).rows.length,1);
  s.setRanking(b.user.id,group.id,true);
  now=Date.parse('2026-10-14T16:00:00Z');
  assert.equal(s.record(a.user.id,'checkin','daily').points,1);
  assert.equal(s.summary(a.user.id).streak,2);
  now=Date.parse('2026-10-17T01:00:00Z');
  assert.equal(s.summary(a.user.id).streak,0);
  s.record(a.user.id,'checkin','daily');assert.equal(s.summary(a.user.id).streak,1);
  now=Date.parse('2026-10-21T01:00:00Z');
  board=s.board(a.user.id,group.id);
  assert.equal(board.rows.find(x=>x.userId===a.user.id).points,0,'Week resets');
  assert.equal(board.rows.find(x=>x.userId===a.user.id).improvement,-7,'Only same elapsed days compared');
  const expired=s.newInvite(a.user.id,group.id);now+=86400001;
  assert.throws(()=>s.previewInvite(expired.code),e=>e.code==='INVITE_UNAVAILABLE');
  const revoked=s.newInvite(a.user.id,group.id);s.revokeInvite(a.user.id,group.id);
  assert.throws(()=>s.previewInvite(revoked.code),e=>e.code==='INVITE_UNAVAILABLE');
  assert.throws(()=>s.leave(a.user.id,group.id),e=>e.code==='TRANSFER_REQUIRED');
  await assert.rejects(()=>s.deleteAccount(a.user.id,password),e=>e.code==='TRANSFER_REQUIRED');
  s.transfer(a.user.id,group.id,b.user.id);
  assert.throws(()=>s.members(a.user.id,group.id),e=>e.status===403);
  s.removeMember(b.user.id,group.id,a.user.id);
  assert.throws(()=>s.board(a.user.id,group.id),e=>e.status===404);
  assert.equal(s.summary(a.user.id).groups.length,0);
  const fresh=await s.login({username:'alice',password});
  await s.changePassword(a.user.id,{currentPassword:password,newPassword:'Changed-password-456!'});
  assert.throws(()=>s.authenticate(fresh.token),e=>e.status===401);
  await assert.rejects(()=>s.login({username:'alice',password}),e=>e.status===401);
  const changed=await s.login({username:'alice',password:'Changed-password-456!'});
  assert.ok(s.exportAccount(a.user.id).events.length>0);
  await s.deleteAccount(a.user.id,'Changed-password-456!');
  assert.throws(()=>s.authenticate(changed.token),e=>e.status===401);
  await assert.rejects(()=>s.login({username:'alice',password:'Changed-password-456!'}),e=>e.status===401);
  await s.deleteAccount(b.user.id,password);
  assert.throws(()=>s.board(c.user.id,group.id),e=>e.status===404);
});
test('SQLite survives restart and stores no raw password or bearer token',async t=>{
  const dir=mkdtempSync(join(tmpdir(),'aca-club-test-')),filename=join(dir,'club.sqlite');
  let s=createService({filename});t.after(()=>{s.close();rmSync(dir,{recursive:true,force:true});});const account=await register(s,'restart');
  s.record(account.user.id,'checkin','daily');s.close();
  const bytes=readFileSync(filename).toString('utf8');
  assert.ok(!bytes.includes(password));assert.ok(!bytes.includes(account.token));
  s=createService({filename});
  assert.equal(s.authenticate(account.token).username,'restart');
  assert.equal(s.summary(account.user.id).checkedIn,true);
  assert.equal(s.record(account.user.id,'checkin','daily').points,0);
});
test('session expires after twelve hours and logout revokes it',async t=>{
  let now=Date.parse('2026-10-14T04:00:00Z');const s=createService({clock:()=>now});t.after(()=>s.close());
  const a=await register(s,'session');s.logout(a.token);assert.throws(()=>s.authenticate(a.token),e=>e.status===401);
  const b=await s.login({username:'session',password});now+=12*3600000;
  assert.throws(()=>s.authenticate(b.token),e=>e.status===401);
});
